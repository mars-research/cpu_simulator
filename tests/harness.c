// Native driver for the uiCA memory tests: runs one loop kernel and prints cycles per iteration.
//
//   harness <kernel> <footprint_bytes> <iters> <reps>
//
// kernel   chase | mchase<K> | rand | pf_t0 | pf_t2   (kernels/<kernel>.s, wrapped by build.sh as k_<kernel>)
// The buffer is backed by 1 GiB pages (no TLB misses); run under `numactl --membind=0 taskset -c 0`.
// chase: the buffer's first footprint/64 lines form one random cycle (Sattolo), one pointer per line;
//        footprints <= 256 MiB are walked once untimed first, so cache-resident chases start warm.
// mchase<K>: the same single cycle, K chains started footprint/64/K lines apart along it (they never
//        meet); one step of every chain per iteration. The K chain pointers live in an L1-resident array.
// others: index kernels; rep r covers indices [r*iters, (r+1)*iters), so reps touch new lines.
// Timing: rdtscp around each rep; the TSC runs at the pinned core clock (2.5 GHz on d760), so
// TSC cycles = core cycles. If PERF_CTL / PERF_ACK name perf's --control fifos, counting is
// enabled only around the timed reps.
#define _GNU_SOURCE
#include <fcntl.h>
#include <linux/mman.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include <unistd.h>
#include <x86intrin.h>

typedef uint64_t (*kernel_fn)(char *buf, uint64_t rsi, uint64_t start);
#include "kernel_table.h"     // generated by build.sh: k_<name> for every kernels/<name>.s

static uint64_t rng = 0x9E3779B97F4A7C15ull;
static uint64_t xorshift(void) { rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return rng; }

static int ctl_fd = -1, ack_fd = -1;
static void perf_ctl(const char *cmd) {
  if (ctl_fd < 0) return;
  char buf[16];
  if (write(ctl_fd, cmd, strlen(cmd)) < 0 || read(ack_fd, buf, sizeof buf) <= 0) { perror("perf ctl"); exit(1); }
}

static char *alloc(size_t sz) {
  size_t gb = (sz + (1ul << 30) - 1) & ~((1ul << 30) - 1);
  char *p = mmap(NULL, gb, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_HUGETLB | MAP_HUGE_1GB, -1, 0);
  if (p == MAP_FAILED) { perror("mmap 1 GiB pages (reserve them on node 0)"); exit(1); }
  memset(p, 0, gb);                       // fault every page in, on the bound node
  return p;
}

int main(int argc, char **argv) {
  if (argc != 5) { fprintf(stderr, "usage: %s <kernel> <footprint_bytes> <iters> <reps>\n", argv[0]); return 1; }
  const char *k = argv[1];
  uint64_t fp = strtoull(argv[2], 0, 0), iters = strtoull(argv[3], 0, 0), reps = strtoull(argv[4], 0, 0);
  int nchains = !strcmp(k, "chase") ? 1 : !strncmp(k, "mchase", 6) ? atoi(k + 6) : 0;
  int chase = nchains > 0;
  kernel_fn fn = NULL;
  for (int i = 0; KERNELS[i].name; i++) if (!strcmp(KERNELS[i].name, k)) fn = KERNELS[i].fn;
  if (!fn) { fprintf(stderr, "unknown kernel %s\n", k); return 1; }
  if (!chase && fp != (1ull << 32)) { fprintf(stderr, "index kernels are hard-wired to a 4 GiB footprint\n"); return 1; }

  char *buf = alloc(fp);
  uint64_t start = 0;
  if (chase) {
    uint64_t n = fp / 64;
    uint32_t *perm = malloc(n * sizeof *perm);
    for (uint64_t i = 0; i < n; i++) perm[i] = i;
    for (uint64_t i = n - 1; i > 0; i--) {          // Sattolo: a single cycle through all n lines
      uint64_t j = xorshift() % i, t = perm[i]; perm[i] = perm[j]; perm[j] = t;
    }
    for (uint64_t i = 0; i < n; i++)
      *(char **)(buf + (uint64_t)perm[i] * 64) = buf + (uint64_t)perm[(i + 1) % n] * 64;
    start = (uint64_t)(buf + (uint64_t)perm[0] * 64);
    if (nchains > 1) {                               // K chains spread evenly along the cycle
      char **ptrs = aligned_alloc(64, 64 * ((nchains * 8 + 63) / 64));
      for (int c = 0; c < nchains; c++) ptrs[c] = buf + (uint64_t)perm[(n / nchains) * c] * 64;
      start = (uint64_t)ptrs;
    }
    free(perm);
    if (fp <= (256ull << 20)) {                      // warm: one full lap
      uint64_t r = fn(buf, n / nchains, start);
      if (nchains == 1) start = r;
    }
  }

  const char *ctl = getenv("PERF_CTL"), *ack = getenv("PERF_ACK");
  if (ctl && ack) { ctl_fd = open(ctl, O_WRONLY); ack_fd = open(ack, O_RDONLY); }

  uint64_t sink = 0;
  unsigned aux;
  perf_ctl("enable\n");
  for (uint64_t r = 0; r < reps; r++) {
    uint64_t s = chase ? start : r * iters;
    uint64_t rsi = chase ? iters : s + iters;
    uint64_t t0 = __rdtscp(&aux);
    uint64_t ret = fn(buf, rsi, s);
    uint64_t t1 = __rdtscp(&aux);
    if (nchains == 1) start = ret; else sink += ret;   // mchase advances its pointer array in place
    printf("rep %lu cycles_per_iter %.4f\n", r, (double)(t1 - t0) / iters);
  }
  perf_ctl("disable\n");
  printf("sink %lu\n", sink + start);
  return 0;
}
